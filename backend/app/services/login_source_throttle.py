import hashlib
import hmac
import ipaddress
from datetime import datetime, timedelta, timezone

from sqlalchemy import func, select, text
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.models import AuditEvent


SOURCE_ATTEMPT_LIMIT = 30
SOURCE_WINDOW = timedelta(minutes=10)

SOURCE_ACTION = "identity.login_source_attempt"
SOURCE_TYPE = "login_source"


class LoginSourceRateLimited(Exception):
    pass


class ClientAddressUnavailable(Exception):
    pass


def normalize_client_address(
    host: str | None,
    *,
    environment: str,
) -> str:
    # Starlette's TestClient uses this synthetic host.
    # It must never be accepted as a real production IP.
    if host == "testclient" and environment == "development":
        return host

    try:
        address = ipaddress.ip_address(host)
    except (ValueError, TypeError):
        raise ClientAddressUnavailable() from None

    if isinstance(address, ipaddress.IPv6Address):
        # Group IPv6 addresses by /64 to limit trivial
        # bypass through temporary interface addresses.
        network = ipaddress.ip_network(
            f"{address}/64",
            strict=False,
        )
        return str(network.network_address) + "/64"

    return str(address)


def source_fingerprint(
    host: str | None,
    *,
    environment: str,
) -> str:
    return _source_digest(
        normalize_client_address(
            host,
            environment=environment,
        )
    )[:16].hex()


def _source_digest(normalized_address: str) -> bytes:
    secret = (
        get_settings()
        .login_throttle_secret
        .get_secret_value()
    )

    if len(secret) < 32:
        raise RuntimeError(
            "Login throttle secret is too short"
        )

    # Domain separation prevents reuse of identifier
    # digests generated by the per-email limiter.
    return hmac.new(
        secret.encode("utf-8"),
        (
            "payflow.login.source.v1:"
            + normalized_address
        ).encode("utf-8"),
        hashlib.sha256,
    ).digest()


def enforce_login_source_limit(
    db: Session,
    *,
    client_address: str | None,
    environment: str,
) -> None:
    """
    Count one login attempt for the caller's source.

    Must execute inside the caller's transaction.

    Uses an independent source bucket, not an
    (IP, email) pair, to detect multi-account attacks.
    """
    normalized = normalize_client_address(
        client_address,
        environment=environment,
    )

    digest = _source_digest(normalized)
    fingerprint = digest[:16].hex()

    lock_key = int.from_bytes(
        digest[:8],
        byteorder="big",
        signed=True,
    )

    # Serialize attempts from this source across
    # PostgreSQL-backed application workers.
    db.execute(
        text("SELECT pg_advisory_xact_lock(:key)"),
        {"key": lock_key},
    )

    cutoff = datetime.now(timezone.utc) - SOURCE_WINDOW

    attempts = db.scalar(
        select(func.count(AuditEvent.id))
        .where(
            AuditEvent.action == SOURCE_ACTION,
            AuditEvent.subject_type == SOURCE_TYPE,
            AuditEvent.subject_id == fingerprint,
            AuditEvent.created_at >= cutoff,
        )
    )

    if attempts >= SOURCE_ATTEMPT_LIMIT:
        raise LoginSourceRateLimited()

    # Count both successful and unsuccessful attempts.
    # Never save the raw IP, email or password here.
    db.add(
        AuditEvent(
            organization_id=None,
            actor_user_id=None,
            action=SOURCE_ACTION,
            subject_type=SOURCE_TYPE,
            subject_id=fingerprint,
            payload={"event": "login_attempt"},
        )
    )

    db.flush()
